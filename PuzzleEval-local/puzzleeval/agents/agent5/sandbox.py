_LOG_PATH = os.environ.get("PUZZLEEVAL_HARNESS_LOG") or "harness_forensics.jsonl"
_T0 = time.monotonic()
_LOCK = threading.Lock()

# Rate-limit: at most this many events per second. Excess events drop with a
# log_throttled summary so a runaway loop can\\'t fill the disk or log file.
_RATE_LIMIT_PER_SEC = 100
_window_start = time.monotonic()
_window_count = 0
_dropped_in_window = 0


# ---------------------------------------------------------------------------
# Credential redaction — MANDATORY before any field hits disk
# ---------------------------------------------------------------------------

_CREDENTIAL_HEADERS = frozenset({
    "authorization", "x-api-key", "xi-api-key", "x-auth-token",
    "openai-api-key", "anthropic-api-key", "x-goog-api-key",
    "bearer", "cookie", "set-cookie",
})

_QUERY_PARAM_REDACT = re.compile(
    r"([?&](?:token|signature|api[_-]?key|access[_-]?token|"
    r"id[_-]?token|key|secret|password|sig)=)[^&#]*",
    re.IGNORECASE,
)


def _redact_url(url):
    """Strip credentials from URL query string. Hostname preserved."""
    if not isinstance(url, str):
        return url
    return _QUERY_PARAM_REDACT.sub(r"\\1[REDACTED]", url)


def _url_host(url):
    """Extract hostname only — never expose path or query params in events."""
    if not isinstance(url, str):
        return None
    # Cheap parser: scheme://host/...  or  scheme://host?...
    m = re.match(r"^[a-zA-Z]+://([^/?#]+)", url)
    return m.group(1) if m else None


def _redact_headers(headers):
    """Replace credential header values with [REDACTED]."""
    if not headers:
        return headers
    try:
        out = {}
        for k, v in dict(headers).items():
            if k.lower() in _CREDENTIAL_HEADERS:
                out[k] = "[REDACTED]"
            elif isinstance(v, str) and v.lower().startswith("bearer "):
                out[k] = "Bearer [REDACTED]"
            else:
                out[k] = v
        return out
    except Exception:
        return "[redaction-failed]"


def _redact_record(record):
    """Walk a record and redact any URL or header field. Mutates in place."""
    if not isinstance(record, dict):
        return record
    if "url" in record:
        record["url"] = _redact_url(record["url"])
    if "headers" in record:
        record["headers"] = _redact_headers(record["headers"])
    return record


# ---------------------------------------------------------------------------
# Core emitter — single chokepoint for all events
# ---------------------------------------------------------------------------

def _emit(record):
    """Append one record to harness_forensics.jsonl. Thread-safe + rate-limited."""
    global _window_start, _window_count, _dropped_in_window

    record["t_ms"] = round((time.monotonic() - _T0) * 1000, 1)
    record["t_abs"] = time.time()
    _redact_record(record)

    with _LOCK:
        now = time.monotonic()
        if now - _window_start >= 1.0:
            # Window roll: emit drop summary if any
            if _dropped_in_window > 0:
                drop_record = {
                    "kind": "event",
                    "event": "log_throttled",
                    "dropped": _dropped_in_window,
                    "t_ms": round((now - _T0) * 1000, 1),
                    "t_abs": time.time(),
                }
                try:
                    with open(_LOG_PATH, "a", encoding="utf-8") as f:
                        f.write(json.dumps(drop_record, default=str) + "\\n")
                except OSError:
                    pass
            _window_start = now
            _window_count = 0
            _dropped_in_window = 0

        if _window_count >= _RATE_LIMIT_PER_SEC:
            _dropped_in_window += 1
            return
        _window_count += 1

        try:
            with open(_LOG_PATH, "a", encoding="utf-8") as f:
                f.write(json.dumps(record, default=str) + "\\n")
        except OSError:
            # Don\\'t crash the harness if the log file isn\\'t writable.
            pass


