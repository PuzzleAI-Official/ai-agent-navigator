def log(event, **kw):
    """Record a canonical event.

    Use canonical event names from the OBSERVABILITY CONTRACT:
      - harness_start, harness_exit
      - session_create_start/done/error
      - request_start/done/error
      - stream_start/event/done/error
      - thread_start/error
      - timeout, provider_error

    Standard fields per event:
      - op (snake_case operation name; builder picks)
      - provider (short tag: "elevenlabs", "openai", "deepgram", ...)
      - url_host (hostname only — NEVER full URL, NEVER query params)
      - status_code, duration_ms, attempt, request_id, error_type, error
    """
    record = {"kind": "event", "event": event}
    record.update(kw)
    _emit(record)


class traced_op:
    """Context manager: auto-pairs op_start/op_done/op_error with timing.

        with traced_op("create_session", provider="elevenlabs"):
            agent_id = create_agent(api_key)

    On entry: emits {event: "op_start", op: "<name>", **kw}
    On clean exit: emits {event: "op_done", op: "<name>", duration_ms, **kw}
    On exception: emits {event: "op_error", op: "<name>", duration_ms,
                          error_type, error, **kw}; re-raises.

    For canonical-taxonomy events (session_create_start, request_done,
    stream_event, etc.), call ``log()`` directly — those are domain-event
    names, distinct from this wrapper pattern. The verifier accepts both:
    it scans the source for ``log("<name>"`` AND ``traced_op("<name>"``
    calls when checking session/stream lifecycle coverage.
    """

    __slots__ = ("op", "kw", "_t0")

    def __init__(self, op, **kw):
        self.op = op
        self.kw = kw
        self._t0 = None

    def __enter__(self):
        self._t0 = time.monotonic()
        record = {
            "kind": "event",
            "event": "op_start",
            "op": self.op,
        }
        record.update(self.kw)
        _emit(record)
        return self

    def __exit__(self, exc_type, exc, tb):
        duration_ms = round((time.monotonic() - self._t0) * 1000, 1)
        if exc is None:
            record = {
                "kind": "event",
                "event": "op_done",
                "op": self.op,
                "duration_ms": duration_ms,
            }
        else:
            record = {
                "kind": "event",
                "event": "op_error",
                "op": self.op,
                "duration_ms": duration_ms,
                "error_type": type(exc).__name__,
                "error": str(exc)[:200],
            }
        record.update(self.kw)
        _emit(record)
        return False  # never swallow exceptions


def log_thread_start(name, **kw):
    """Record a background thread starting."""
    record = {"kind": "thread", "event": "thread_start", "name": name,
              "tid": threading.get_ident()}
    record.update(kw)
    _emit(record)


def log_thread_error(name, error, **kw):
    """Record an uncaught exception in a background thread."""
    record = {
        "kind": "thread",
        "event": "thread_error",
        "name": name,
        "tid": threading.get_ident(),
        "error_type": type(error).__name__ if isinstance(error, BaseException) else "Error",
        "error": str(error)[:200],
        "tb": traceback.format_exc()[:1000],
    }
    record.update(kw)
    _emit(record)


