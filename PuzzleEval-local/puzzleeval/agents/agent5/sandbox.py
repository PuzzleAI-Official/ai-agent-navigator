def _install_requests_hook():
    try:
        import requests
        orig = requests.Session.request
        if getattr(orig, "_puzzleeval_traced", False):
            return
        def traced(self, method, url, **kw):
            t0 = time.monotonic()
            host = _url_host(url)
            try:
                r = orig(self, method, url, **kw)
                _emit({"kind": "http", "event": "request_done",
                       "method": method, "url_host": host,
                       "status_code": r.status_code,
                       "duration_ms": round((time.monotonic()-t0)*1000, 1)})
                return r
            except Exception as exc:
                _emit({"kind": "http", "event": "request_error",
                       "method": method, "url_host": host,
                       "duration_ms": round((time.monotonic()-t0)*1000, 1),
                       "error_type": type(exc).__name__,
                       "error": str(exc)[:200]})
                raise
        traced._puzzleeval_traced = True
        requests.Session.request = traced
    except Exception:
        pass


