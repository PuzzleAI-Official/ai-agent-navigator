def _install_threading_hook():
    """Auto-emit thread_start on Thread.start() + thread_error on uncaught."""
    try:
        orig_start = threading.Thread.start
        if getattr(orig_start, "_puzzleeval_traced", False):
            return

        def traced_start(self):
            try:
                _emit({"kind": "thread", "event": "thread_start",
                       "name": getattr(self, "name", "?")})
            except Exception:
                pass
            return orig_start(self)
        traced_start._puzzleeval_traced = True
        threading.Thread.start = traced_start

        orig_run = threading.Thread.run
        def traced_run(self):
            try:
                return orig_run(self)
            except BaseException as exc:
                try:
                    log_thread_error(getattr(self, "name", "?"), exc)
                except Exception:
                    pass
                raise
        traced_run._puzzleeval_traced = True
        threading.Thread.run = traced_run
    except Exception:
        pass


